const RTL = new Set<Locale>(["ar"]);

let locale: Locale = "en";
const listeners = new Set<() => void>();

export function detectLocale(raw?: string | null): Locale {
  const pool =
    raw
      ? [raw]
      : typeof navigator === "undefined"
        ? ["en"]
        : [...(navigator.languages ?? []), navigator.language || "en"];
  for (const item of pool) {
    const low = String(item || "").toLowerCase();
    if (!low) continue;
    const full = ALIAS[low];
    if (full) return full;
    const base = ALIAS[low.split("-")[0] ?? ""];
    if (base) return base;
  }
  return "en";
}

function applyDoc(next: Locale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = next;
  document.documentElement.dir = RTL.has(next) ? "rtl" : "ltr";
}

export function getLocale(): Locale {
  return locale;
}

export function setLocale(next: Locale) {
  if (locale === next) {
    applyDoc(next);
    return;
  }
  locale = next;
  applyDoc(next);
  listeners.forEach((fn) => fn());
}

export function bootLocale() {
  setLocale(detectLocale());
}

export function t(key: Msg, vars?: Record<string, string | number>): string {
  const pack = PACK[locale] ?? EN;
  let s = pack[key] ?? EN[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function useT() {
  const [, bump] = useState(0);
  useEffect(() => {
    const fn = () => bump((n) => n + 1);
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  }, []);
  return t;
}

export function useLocale(): Locale {
  useT();
  return locale;
}
